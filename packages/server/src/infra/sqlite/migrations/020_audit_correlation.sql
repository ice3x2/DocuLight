-- 묶음 경계를 기록 시점에 정한다 (`IR-AUDIT-003` AC-8 · AC-9 · 원장 `R164-c`).
--
-- 개정 전에는 뷰어가 「같은 초 · 같은 조작 · 같은 행위자」로 묶었다.
-- `occurred_at` 이 초 단위(`datetime('now')`)라 한 사람이 같은 초에 문서를
-- 둘 만들면 그 둘이 한 줄로 접혔고, 열람자는 조작 하나로 읽었다. 반대로
-- 서브트리 삭제가 초 경계를 넘으면 한 조작이 두 줄로 갈렸다.
--
-- 정밀도를 올리는 것은 충돌 확률만 낮추고 「경계가 시간에 종속된다」는
-- 구조를 남긴다. 그래서 경계 자체를 값으로 적는다.
--
-- **이 칸은 조회 응답에 실리지 않는다** (같은 요구 AC-5·AC-6·AC-7). 두
-- 워크스페이스의 행에 같은 값이 실리므로, 노출하면 행 간 상관으로 상대편을
-- 복원할 수 있다 — `R138-b` 가 가명·연번을 금지한 것과 같은 취약점이다.
-- 그래서 `DR-AUDIT-002` AC-7 의 의미 칸 열하나에도 세지 않는다.
--
-- 기존 행은 `NULL` 로 남고 **백필하지 않는다.** 뷰어는 그때 행 자신의 id 로
-- 접어 낱행 하나짜리 묶음을 만든다.
--
-- 이것이 표시 후퇴라는 것을 숨기지 않는다 — 개정 전에는 같은 초의 옛 서브트리
-- 삭제 3행이 1줄로 보였고 이제 3줄로 보인다. 그럼에도 백필하지 않는 이유는,
-- 옛 키(`조작+행위자+초`)를 값으로 굳히면 **같은 초의 서로 다른 두 조작이
-- 한 묶음이라는 거짓**이 저장소에 영구히 박히기 때문이다. 그 거짓을 막는 것이
-- 이 칸을 만든 이유(AC-8)이고, 감사 행은 고칠 수 없다(`OBS-AUDIT-002`).
--
-- 그래서 옛 행에 대해 AC-8(잘못 합치지 않는다)은 성립하고 AC-9(한 조작은
-- 함께 접힌다)는 성립하지 않는다 — 경계를 기록한 적이 없으므로 알 수 없고,
-- 모르는 것을 지어내지 않는다.
--
-- 인덱스를 두지 않는다. 접기는 스코프로 이미 좁혀진 결과 위에서 메모리
-- 안에서 일어나므로 이 칸으로 거르거나 조인하는 질의가 없고, 쓰기 비용만
-- 남는다. 그런 질의가 생기는 날 그 커밋이 함께 세우면 된다.
