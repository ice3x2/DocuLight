-- 첨부의 **원본 파일명** (`DR-ATTACH-002` AC-4 · 원장 `R149-g`).
--
-- 디스크에 놓이는 이름은 해시다(`R50`). 그래서 업로드 시점에 여기 적지
-- 않으면 그 이름은 **어떤 마이그레이션으로도 되살릴 수 없다** — 이 칸은
-- 검색을 위한 것이기 이전에 데이터 소실을 막는 자리다.
--
-- 소유 문서마다 행이 서므로(`014` 의 기본키) 이름도 소유 문서마다 다를 수
-- 있다. 같은 바이트를 두 사람이 각자의 이름으로 올린 경우이며, 해시 단위로
-- 두면 볼 수 없는 문서가 붙인 이름이 볼 수 있는 문서 아래로 샌다.
--
-- 기존 행은 이름을 되살릴 수 없으므로 빈 문자열로 둔다. `NOT NULL` 로
-- 두는 이유는 앞으로 들어오는 행에 이름이 빠지는 것을 막기 위해서다 —
-- 되살릴 수 없는 값은 처음부터 안 빠지게 하는 것 말고 방법이 없다.
ALTER TABLE attachment ADD COLUMN original_name TEXT NOT NULL DEFAULT '';
