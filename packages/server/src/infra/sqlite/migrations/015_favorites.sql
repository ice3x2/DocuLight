-- 즐겨찾기 (FR-SHELL-001 AC-3 · AC-4).
--
-- 주체와 노드가 함께 기본키다 — 같은 것을 두 번 더해도 줄이 하나여야
-- 하기 때문이다. 두 줄이 되면 뺄 때 하나가 남고, 남은 줄은 목록에
-- 중복으로 나타나기 전까지 아무도 눈치채지 못한다.
--
-- **더한 시각 칸이 없다.** 목록의 순서는 더한 순서인데 그것은 rowid 가
-- 이미 아는 사실이다 — 칸을 두면 시계를 여기까지 끌어와야 하고, 시계가
-- 닿는 곳마다 시험이 시계를 흉내내야 한다.
--
-- **디렉토리도 담는다.** 문서만 담으면 디렉토리를 즐겨찾기한 사용자가
-- 그것을 다시 찾지 못한다 — 노드 종류는 여기 적지 않고 노드 저장소에서
-- 읽는다. 두 곳이 들면 이름이 바뀔 때 한쪽만 바뀐다.
CREATE TABLE favorite (
  subject_id TEXT NOT NULL,
  node_id    TEXT NOT NULL,
  PRIMARY KEY (subject_id, node_id)
);
