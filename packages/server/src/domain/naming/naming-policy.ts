/**
 * 이름 규칙의 **값이 사는 유일한 자리** (`FR-WORKSPACE-004` · `R40-e`).
 *
 * 원장에 값이 없어 열려 있던 세 축을 2026-08-21 에 닫은 결과다. 검증기도
 * 테스트도 여기서 읽는다 — 값을 두 곳에 두면 한쪽만 고쳐지고 다른 쪽이
 * 조용히 어긋난다.
 */

/**
 * 이름 하나의 상한. **문자 수가 아니라 UTF-8 바이트**다.
 *
 * NTFS 는 UTF-16 코드 단위 255, ext4 는 255바이트로 단위가 갈린다. 바이트로
 * 재면 어느 쪽도 넘지 않는다. 대가는 한글 실질 85자이고, 그래서 거부 문구가
 * 바이트 한계임을 드러내야 한다(`AC-7`).
 */
export const MAX_NAME_BYTES = 255;

/**
 * 워크스페이스 루트 기준 **상대** 경로의 상한 (UTF-8 바이트).
 *
 * `MAX_PATH` 260 을 쓰지 않는 이유 — 그것은 드라이브 문자부터 세는 절대
 * 경로 한계라 `docsRoot` 위치에 따라 배포마다 판정이 갈린다.
 *
 * 값은 AC 자체에서 나온다. 경로 상한이 이름 상한의 두 배에 못 미치면
 * **`AC-5` 가 허용하는 이름을 `AC-6` 이 거부하는 자기모순**이 생긴다 —
 * 상한 길이 디렉토리 아래에 상한 길이 파일을 둘 수 없기 때문이다.
 * `255 × 2 + 2`(구분자 여유) = 512 가 두 AC 를 동시에 성립시키는 최소값이다.
 */
export const MAX_RELATIVE_PATH_BYTES = 512;

/** 경로 구분자. 경로는 항상 이 문자로 잇는다. */
export const PATH_SEPARATOR = '/';

/**
 * Win32 예약 문자 아홉.
 *
 * `/` 와 `\` 가 들어 있는 것이 핵심이다 — 이름에 구분자가 들어가면 이름
 * 하나가 경로 여러 단계로 읽혀 `..` 없이도 상위로 새어 나간다.
 */
export const FORBIDDEN_CHARACTERS: readonly string[] = [
  '<',
  '>',
  ':',
  '"',
  '/',
  '\\',
  '|',
  '?',
  '*',
];

/**
 * 예약 장치 이름 — `R40-e` 의 `등` 을 닫은 목록이다.
 *
 * **상첨자 변종 여섯을 빠뜨리기 쉽다.** Windows 가 `¹`·`²`·`³` 를 숫자로
 * 인식해 `COM#`·`LPT#` 의 일부로 취급하므로 그 이름들도 모든 디렉토리에서
 * 예약된다.
 */
export const RESERVED_DEVICE_NAMES: readonly string[] = [
  'CON',
  'PRN',
  'AUX',
  'NUL',
  ...Array.from({ length: 9 }, (_, i) => `COM${i + 1}`),
  'COM¹',
  'COM²',
  'COM³',
  ...Array.from({ length: 9 }, (_, i) => `LPT${i + 1}`),
  'LPT¹',
  'LPT²',
  'LPT³',
];
