/**
 * 재조정 대기열 항목의 보존 만료 소멸 경계 (`REL-AUDIT-003` · 원장 `G37`).
 *
 * **`FindingQueue` 와 나눠 둔다.** `AuditRetention` 이 `AuditSink` 에서 갈라져
 * 나온 근거가 그대로 적용된다 — 대기열을 여닫는 쪽에 지우는 메서드를 얹으면
 * 「항목은 해소될 때까지 남는다」를 지키는 방법이 그 인터페이스에서 사라진다.
 * 소멸은 사람의 조작이 아니라 기간이 하는 일이라 부르는 자리도 다르므로,
 * 경계를 따로 두면 **누가 이것을 쥐고 있는가**가 타입으로 드러난다.
 */
export interface FindingRetention {
  /**
   * 그 시각 **이전**의 감사 행을 하나라도 참조하는 항목을 지우고 지운
   * 개수를 돌려준다.
   *
   * **가장 이른 참조가 수명을 정한다.** 「모두 만료해야 소멸」로 두면 살아남은
   * 참조가 만료한 참조를 다시 붙들어, 감사 보존 기간이 대기열에 걸린 행에
   * 한해 무기한이 된다.
   *
   * 경계값을 호출자가 계산해 넘기는 이유는 `AuditRetention.purgeBefore` 와
   * 같다 — 「지금」이 도메인 밖의 사실이고, 두 소멸이 **같은 경계값**을 봐야
   * 한쪽만 지워지는 상태가 생기지 않는다.
   */
  purgeReferencing(cutoff: string): number;
}
