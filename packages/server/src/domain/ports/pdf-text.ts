/**
 * PDF 본문 추출 경계 (`FR-SHELL-013` AC-4).
 *
 * 검색이 PDF 를 본문 축으로 덮으려면 그 바이트에서 글자를 얻어야 하는데,
 * 그 일은 도메인의 일이 아니다 — 어떤 라이브러리를 쓰는지는 바깥의 사정이고
 * 도메인이 그것을 알면 경계가 사라진다. 그래서 이 자리는 「무엇을 돌려받는가」
 * 만 정한다.
 *
 * **페이지 번호를 함께 돌려주는 것이 이 포트의 존재 이유다.** 조항이 색인
 * 항목에 페이지 번호를 실으라고 요구하므로, 전체 글자를 한 덩어리로 돌려주는
 * 추출기로는 그 요구를 만족할 수 없다.
 */

/** 한 페이지에서 얻은 글자. */
export interface PdfPageText {
  /** 1 부터 센다 — 사람이 읽는 번호와 같아야 한다. */
  readonly page: number;
  readonly text: string;
}

export interface PdfTextExtractor {
  /**
   * 페이지마다 글자를 뽑는다. 글자가 없는 페이지도 빈 문자열로 자리를
   * 지킨다 — 자리를 빼면 뒤 페이지의 번호가 밀린다.
   *
   * 읽을 수 없는 바이트에는 빈 배열을 돌려준다. 검색 한 건 때문에 조회
   * 전체가 실패할 일이 아니다.
   */
  extract(bytes: Uint8Array): Promise<readonly PdfPageText[]>;
}
