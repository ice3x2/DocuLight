/**
 * 감사 행의 보존 만료 소멸 경계 (`REL-AUDIT-003`).
 *
 * **`AuditSink` 와 나눠 둔다.** 그쪽은 추가만 여는 것이 불변성을 지키는
 * 방법이고(`OBS-AUDIT-002`), 거기에 지우는 메서드를 얹으면 그 방법이
 * 사라진다. 소멸은 사람의 조작이 아니라 기간이 하는 일이라 부르는 자리도
 * 다르므로, 경계를 따로 두면 **누가 이것을 쥐고 있는가**가 타입으로 드러난다.
 */
export interface AuditRetention {
  /**
   * 그 시각 **이전**의 감사 행을 지우고 지운 개수를 돌려준다.
   *
   * 경계값을 호출자가 계산해 넘기는 이유는 「지금」이 도메인 밖의 사실이기
   * 때문이다 — 어댑터가 시계를 읽으면 그 판정을 시험할 수 없다.
   */
  purgeBefore(cutoff: string): number;
}
